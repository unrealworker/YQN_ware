'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const { readMetrics, BudgetPolicy } = require('../server/resource-budget');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const sample = (id, time, appliedFps, actualFps, gpuMs = 10) => ({ id, receivedAt: time, appliedFps, actualFps, gpuMs });
test('stateful budget waits for warmup and acknowledged fresh samples, then restores capacity immediately for one viewer', () => {
  const p = new BudgetPolicy({ mode: 'independent', fps: 60 });
  assert.equal(p.update([null, null], 0), 30);
  assert.equal(p.update([sample('a', 2000, 30, 30), sample('b', 2000, 30, 30)], 2000), 30);
  assert.equal(p.update([sample('a', 6000, 60, 60), sample('b', 6000, 30, 30)], 6000), 30);
  assert.equal(p.update([sample('a', 7000, 30, 30), sample('b', 7000, 30, 30)], 7000), 30);
  assert.equal(p.update([sample('a', 8000, 30, 30), null], 8000), 30);
  assert.equal(p.update([sample('a', 8000, 30, 30)], 8000), 60);
  assert.equal(p.update([null, null, null], 9000), 20);
});
test('two observed low-fps intervals apply a fair cap, duplicate telemetry is not counted, and recovery waits twelve seconds', () => {
  const p = new BudgetPolicy({ mode: 'independent', fps: 60 });
  p.update([null, null], 0);
  const low = [sample('a', 6000, 30, 18), sample('b', 6000, 30, 20)];
  assert.equal(p.update(low, 6000), 30);
  assert.equal(p.update(low, 7000), 30);
  assert.equal(p.update([sample('a', 8000, 30, 18), sample('b', 8000, 30, 20)], 8000), 22);
  assert.equal(p.update([sample('a', 10000, 22, 22), sample('b', 10000, 22, 22)], 10000), 17);
  assert.equal(p.update([sample('a', 18000, 17, 17), sample('b', 18000, 17, 17)], 18000), 17);
  assert.equal(p.update([sample('a', 21000, 17, 17), sample('b', 21000, 17, 17)], 21000), 17);
  assert.equal(p.update([sample('a', 23000, 17, 17), sample('b', 23000, 17, 17)], 23000), 19);
});
test('real three-instance GPU wait measurements cannot reduce a delivered twenty-fps budget', () => {
  const p = new BudgetPolicy({ mode: 'independent', fps: 60 });
  assert.equal(p.update([null, null, null], 0), 20);
  const m = time => [sample('a', time, 20, 20, 27), sample('b', time, 20, 20, 27), sample('c', time, 20, 20, 15)];
  assert.equal(p.update(m(6000), 6000), 20);
  assert.equal(p.update(m(8000), 8000), 22);
  assert.equal(p.update([sample('a', 10000, 22, 22, 250), sample('b', 10000, 22, 22, 250), sample('c', 10000, 22, 22, null)], 10000), 22);
  assert.equal(p.update([sample('a', 12000, 22, 22, null), sample('b', 12000, 22, 22, NaN), sample('c', 12000, 22, 22, 500)], 12000), 24);
});
test('missing GPU timings still permit pressure detection and shared or disabled mode keeps full target', () => {
  const p = new BudgetPolicy({ mode: 'independent', fps: 60 });
  p.update([null, null], 0);
  assert.equal(p.update([sample('a', 6000, 30, 20, null), sample('b', 6000, 30, 20, null)], 6000), 30);
  assert.equal(p.update([sample('a', 8000, 30, 20, null), sample('b', 8000, 30, 20, null)], 8000), 22);
  assert.equal(new BudgetPolicy({ mode: 'shared', fps: 60 }).update([null, null, null], 0), 60);
  assert.equal(new BudgetPolicy({ mode: 'independent', fps: 60, adaptiveResourceBudget: false }).update([null, null, null], 0), 60);
});
test('an expired pressure hold does not promote a newly struggling instance', () => {
  const p = new BudgetPolicy({ mode: 'independent', fps: 60 });
  p.update([null, null], 0);
  p.update([sample('a', 6000, 30, 18), sample('b', 6000, 30, 18)], 6000);
  p.update([sample('a', 8000, 30, 18), sample('b', 8000, 30, 18)], 8000);
  p.update([sample('a', 10000, 22, 22), sample('b', 10000, 22, 22)], 10000);
  assert.equal(p.update([sample('a', 21000, 17, 8), sample('b', 21000, 17, 8)], 21000), 17);
});
test('probing requires consecutive healthy samples, a four-second interval and fresh acknowledgements', () => {
  const p = new BudgetPolicy({ mode: 'independent', fps: 60 });
  p.update([null, null], 0);
  const m = (time, applied = 30, actual = applied) => [sample('a', time, applied, actual), sample('b', time, applied, actual)];
  assert.equal(p.update(m(6000), 6000), 30);
  assert.equal(p.update(m(6000), 7000), 30);
  assert.equal(p.update(m(8000, 30, 27), 8000), 30);
  assert.equal(p.update(m(10000), 10000), 30);
  assert.equal(p.update(m(12000), 12000), 32);
  assert.equal(p.update(m(14000, 32), 14000), 32);
  assert.equal(p.update(m(15000, 32), 15000), 32);
  assert.equal(p.update(m(16000, 32), 16000), 34);
  assert.equal(p.update(m(9000, 34), 17000), 34);
  assert.equal(p.update(m(18000, 32), 18000), 34);
});
test('metrics reader only accepts fresh bounded local telemetry and tolerates atomic replace and malformed data', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ghs-metrics-test-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const file = path.join(dir, 'metrics.json');
  assert.equal(readMetrics(dir), null);
  fs.writeFileSync(file, '{'); assert.equal(readMetrics(dir), null);
  fs.writeFileSync(file, JSON.stringify({ version: 1, sequence: 3, appliedFps: 30, actualFps: 29.5, gpuMs: 10, screenPercentage: 100 }));
  assert.equal(readMetrics(dir).actualFps, 29.5);
  fs.utimesSync(file, new Date(0), new Date(0)); assert.equal(readMetrics(dir), null);
  fs.writeFileSync(file, JSON.stringify({ version: 1, sequence: 3, appliedFps: 30, actualFps: 10000 }));
  assert.equal(readMetrics(dir), null);
});
