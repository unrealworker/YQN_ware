"""Validate the scoped worker selection against CAD and generate cooked data.

This changes presentation selection only. The original 256 CAD personnel,
worktable evidence, central feed mapping and exchange scheduler are preserved.
"""
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[2]
POLICY = ROOT / "SourceAssets/MPR/sorter_simulation/worker_presentation_policy.json"
HEADER = ROOT / "Source/Test/MPRWorkerPresentationPolicy.h"


def generate():
    policy = json.loads(POLICY.read_text(encoding="utf-8"))
    cad = json.loads((ROOT / policy["source_record"]).read_text(encoding="utf-8"))
    layout = json.loads((ROOT / "SourceAssets/MPR/sorter_simulation/layout.json").read_text(encoding="utf-8"))
    assert policy["schema_version"] == 1
    assert cad["source_sha256"] == policy["source_cad_sha256"]
    assert len(cad["workers"]) == cad["count"] == policy["source_worker_count"]
    source = {worker["source_handle"]: worker for worker in cad["workers"]}
    assert len(source) == cad["count"], "Source handles must be unambiguous"
    retained = policy["retained_workers"]
    handles = {worker["source_handle"] for worker in retained}
    assert len(handles) == len(retained), "Duplicate retained worker"
    assert handles <= source.keys(), "Retained worker missing from original CAD"
    feed = {worker["source_handle"] for worker in cad["workers"] if worker["central_feed"]}
    assert {worker["source_handle"] for worker in retained if worker["role"] == "central_feed"} == feed
    assert all(worker["role"] in ("central_feed", "sorter_console") for worker in retained)
    console = {worker["source_handle"] for worker in retained if worker["role"] == "sorter_console"}
    console_evidence = {station["worker_source_handle"] for station in cad["operator_stations"]}
    assert console <= console_evidence, "Sorter console must have original equipment evidence"
    expected = {
        "retained_cad_workers": len(retained),
        "omitted_cad_workers": len(source) - len(retained),
        "manual_feed_workers": len(feed),
        "sorter_console_workers": len(console),
        "exchange_worker_slots": len(layout["machines"]),
        "runtime_worker_slots": len(layout["machines"]) + len(retained),
        "idle_visible_workers": len(retained),
        "maximum_visible_workers": len(retained) + 1,
    }
    assert policy["expected_counts"] == expected, "Policy counts must match CAD and actual sorter layout"
    lines = [
        "// Generated by generate_mpr_worker_presentation_policy.py. Do not edit.",
        "// Exact source-handle selection; original MPRCadWorkerData remains complete.",
        "#pragma once", "#include <cstring>", "namespace MPRWorkerPresentation", "{",
        "struct Entry { const char* SourceHandle; const char* Role; };",
        "inline constexpr Entry RetainedWorkers[] = {",
    ]
    lines += [f'    {{"{worker["source_handle"]}","{worker["role"]}"}},' for worker in retained]
    lines += ["};", f"inline constexpr int SourceWorkerCount = {len(source)};",
              f"inline constexpr int RetainedWorkerCount = {len(retained)};",
              "inline const Entry* Find(const char* SourceHandle)", "{",
              "    for (const auto& Worker : RetainedWorkers)",
              "        if (std::strcmp(Worker.SourceHandle, SourceHandle) == 0) return &Worker;",
              "    return nullptr;", "}", "}", ""]
    return "\n".join(lines), expected


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate the committed header without writing")
    args = parser.parse_args()
    header, expected = generate()
    if args.check:
        assert HEADER.read_text(encoding="utf-8") == header, "Generated worker policy header is stale"
    else:
        HEADER.write_text(header, encoding="utf-8", newline="\n")
    print(json.dumps({"verified": True, "expected_counts": expected}, ensure_ascii=False))
