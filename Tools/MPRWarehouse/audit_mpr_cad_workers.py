"""Extract every instanced personnel symbol from the original MPR modelspace.

Read-only CAD audit. Standing-body XY follows the source head/torso projection;
height and Manny scale are display choices, not surveyed elevations.
The recursive scan preserves INSERT chains and mirrored coordinate transforms.
"""
from pathlib import Path
import collections
import hashlib
import io
import json
import math
import os
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'Scripts/_vendor/cad'))
# Use the portable parser/math implementation for this large read-only audit;
# the vendored optional native modules vary with the host Python runtime.
os.environ['EZDXF_DISABLE_C_EXT'] = '1'
import ezdxf
from ezdxf import bbox, path
from ezdxf.math import BoundingBox, Matrix44
from PIL import Image, ImageDraw, ImageFont

SOURCE = Path('D:/Data/仓库数据/MPR/平面布局图_MPR规划图V1.1_ALL-IN-ONE_0921.dxf')
OUT = ROOT / 'SourceAssets/MPR/sorter_simulation/cad_workers'
PERSON_BLOCKS = {'terwrq434', '作业工人', 'UNI_LIB (2D)-407', 'KN_UNI_060100101 (2D)'}
FEED_HANDLES = {'2CCF63', '2CCF64', '2CCF65', '2CCF69', '2CCF67', '2CCF68'}
HEAD_LINES = ['15FED','15FF4','15FF5','1600C','1600F','16011','16015','16018','1601E','1601F','16020','16032','16065','16067','16070','16074','16077','16079','1607D','1607E','16081']
SHOE_LINES = [['15FFF','16004','16006','1600A','1600B','1600D'], ['16023','16024','16026','16029','1602A','1602F']]
EXPECTED_SHA = 'c316aafe183162c5bef636885b59cc1000c3eecf50d8be645490b4716c6af863'


def read_personnel_document():
    """Preserve the complete INSERT graph without allocating all CAD linework."""
    selected = []
    section = block_name = ''

    def keep(record):
        nonlocal section, block_name
        if not record:
            return
        kind = record[0][1].strip()
        values = {code: value.strip() for code, value in record}
        if kind == 'SECTION':
            section = values.get(2, '')
        if kind == 'BLOCK':
            block_name = values.get(2, '')
        retain = section in ('HEADER', 'TABLES') or kind in ('SECTION', 'ENDSEC', 'EOF')
        if section == 'BLOCKS':
            retain |= kind in ('BLOCK', 'ENDBLK', 'INSERT', 'ATTRIB', 'SEQEND') or block_name in PERSON_BLOCKS or (block_name == 'GIE2' and values.get(5) in ('10A50D', '10A50E'))
        if section == 'ENTITIES':
            retain |= kind in ('INSERT', 'ATTRIB', 'SEQEND')
        if retain:
            selected.extend(f'{code}\n{value}\n' for code, value in record)
        if kind == 'ENDBLK':
            block_name = ''

    def decode(value):
        try:
            return value.decode('utf8').rstrip('\r\n')
        except UnicodeDecodeError:
            return value.decode('gb18030', errors='replace').rstrip('\r\n')
    with SOURCE.open('rb') as stream:
        record = []
        while True:
            code_line, value_line = stream.readline(), stream.readline()
            if not code_line:
                break
            code = int(code_line)
            if code == 0:
                keep(record); record = []
            record.append((code, decode(value_line)))
        keep(record)
    return ezdxf.read(io.StringIO(''.join(selected)))


def emit_header(data):
    lines = ['// Generated by audit_mpr_cad_workers.py from all recursively instanced CAD personnel.',
             '// Standing-body anchors use source head/torso projections; Z=0 is the display floor.',
             '#pragma once', 'namespace MPRCadWorkers', '{',
             'struct Worker { const char* SourceHandle; double Feet[3]; double Yaw; bool CentralFeed; };',
             'inline constexpr Worker Workers[] = {']
    for w in data['workers']:
        x, y, _ = w['feet_ue_cm']
        lines.append('    {"%s",{%.8f,%.8f,0.},%.8f,%s},' %
                     (w['source_handle'], x, y, w['facing_ue_yaw_deg'], str(w['central_feed']).lower()))
    lines += ['};', 'struct WorkTable { double OldCenter[3]; double OldScale[3]; double OldYaw; double Centers[2][3]; double SizeCm[2]; double Yaw[2]; };', 'inline constexpr WorkTable WorkTables[] = {']
    fmt = lambda p: '{'+','.join(f'{v:.8f}' for v in p)+'}'
    for t in data['work_tables']:
        lines.append('    {'+','.join([fmt(t['legacy_center_ue_cm']),fmt(t['legacy_scale']),f"{t['legacy_yaw_deg']:.8f}",'{'+','.join(fmt(s['center_ue_cm']) for s in t['surfaces'])+'}',fmt([180.,100.]),fmt([s['yaw_deg'] for s in t['surfaces']])])+'},')
    lines += ['};', f"inline constexpr int Count={data['count']};",
              f"inline constexpr int CentralFeedCount={data['central_feed_count']};",
              f'inline constexpr const char* SourceSha256="{data["source_sha256"]}";', '}']
    target = ROOT / 'Source/Test/MPRCadWorkerData.h'
    content = '\n'.join(lines) + '\n'
    if not target.exists() or target.read_text(encoding='utf8') != content:
        target.write_text(content, encoding='utf8')


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    with SOURCE.open('rb') as stream:
        digest = hashlib.file_digest(stream, 'sha256').hexdigest()
    assert digest == EXPECTED_SHA, 'CAD changed: repeat personnel symbol classification.'
    print('Reading original CAD', flush=True)
    doc = read_personnel_document()
    contains_cache, bounds_cache = {}, {}

    def contains_person(name, ancestors=()):
        if name in PERSON_BLOCKS:
            return True
        if name in ancestors:
            return False
        if name not in contains_cache:
            contains_cache[name] = any(contains_person(e.dxf.name, ancestors + (name,))
                                       for e in doc.blocks[name] if e.dxftype() == 'INSERT')
        return contains_cache[name]

    workers = []
    head_bounds = bbox.extents([doc.entitydb[h] for h in HEAD_LINES], fast=True)
    shoe_centres = [bbox.extents([doc.entitydb[h] for h in hs], fast=True).center for hs in SHOE_LINES]

    def anchor(name):
        if name == 'terwrq434':
            return head_bounds.center, HEAD_LINES
        # Other wrappers only reorient the same UNI head outline.
        def find(es, mt, ids=()):
            for e in es:
                if e.dxf.handle == '1D6D9E':
                    return mt.transform(bbox.extents([e], fast=True).center), list(ids)+( [e.dxf.handle])
                if e.dxftype() == 'INSERT':
                    result = find(doc.blocks[e.dxf.name], Matrix44.chain(e.matrix44(), mt), ids+(e.dxf.handle,))
                    if result:
                        return result
        return find(doc.blocks[name], Matrix44())

    def ue(p): return [(p[0]-12800.)*2.54, -(p[1]-8000.)*2.54, 0.]

    def walk(entities, matrix, handles=(), blocks=()):
        for e in entities:
            if e.dxftype() != 'INSERT' or not contains_person(e.dxf.name):
                continue
            mt = Matrix44.chain(e.matrix44(), matrix)
            ids, names = handles + (e.dxf.handle,), blocks + (e.dxf.name,)
            if e.dxf.name not in PERSON_BLOCKS:
                walk(doc.blocks[e.dxf.name], mt, ids, names)
                continue
            # Stop at the first recognized wrapper; its nested person is the
            # same drawn individual, not another worker to spawn on top.
            if e.dxf.name not in bounds_cache:
                bounds_cache[e.dxf.name] = bbox.extents(doc.blocks[e.dxf.name], fast=True)
            world = BoundingBox(mt.transform_vertices(bounds_cache[e.dxf.name].cube_vertices()))
            c = world.center
            body_local, anchor_handles = anchor(e.dxf.name)
            body = mt.transform(body_local)
            axis = mt.transform_direction((1, 0, 0))
            source_id = '/'.join(ids)
            workers.append({'source_handle': source_id, 'source_handles': list(ids), 'blocks': list(names),
                            'center_dxf': list(c), 'bounds': [list(world.extmin), list(world.extmax)],
                            'axis': list(axis), 'feet_ue_cm': ue(body),
                            'legacy_bbox_center_ue_cm': ue(c), 'body_anchor_dxf': list(body),
                            'anchor_source_handles': anchor_handles,
                            'anchor_basis': 'Original head/torso projection centre for upright Manny; excludes extended arms and projected toes.',
                            'shoe_midpoint_ue_cm': ue(mt.transform((shoe_centres[0]+shoe_centres[1])*.5)) if e.dxf.name == 'terwrq434' else None,
                            'facing_ue_yaw_deg': math.degrees(math.atan2(-axis.y, axis.x)),
                            'central_feed': len(ids) == 1 and source_id in FEED_HANDLES})

    walk(doc.modelspace(), Matrix44())
    counts = collections.Counter('/'.join(w['blocks']) for w in workers)
    assert len(workers) == 256 and sum(w['central_feed'] for w in workers) == 6
    assert len({w['source_handle'] for w in workers}) == len(workers)
    assert all(5400 <= w['center_dxf'][0] <= 20200 and 4200 <= w['center_dxf'][1] <= 11400 for w in workers)
    separation = min(math.dist(a['feet_ue_cm'], b['feet_ue_cm'])
                     for i, a in enumerate(workers) for b in workers[i+1:])
    assert separation > 30, 'Overlapping source symbols require manual duplicate review.'
    operations = json.loads((ROOT/'SourceAssets/MPR/operations/instances.json').read_text(encoding='utf8'))['instances']
    tables = []
    for e in doc.modelspace():
        if e.dxftype() != 'INSERT' or e.dxf.name != 'GIE2':
            continue
        old = next(r for r in operations if r['mesh'] == 'SM_MPR_WorkTable' and r['source_handles'] == [e.dxf.handle])
        t = {'source_handle':e.dxf.handle, 'legacy_center_ue_cm':[old['position_m'][0]*100,-old['position_m'][1]*100,0.],
             'legacy_scale':old['scale'], 'legacy_yaw_deg':-old['rotation_deg'], 'surfaces':[]}
        people = [w for w in workers if w['source_handles'][0] == e.dxf.handle]
        assert len(people) == 2
        for h in ['10A50D','10A50E']:
            surface = doc.entitydb[h]
            pts = list(e.matrix44().transform_vertices(surface.vertices_in_wcs()))
            centre = ue(BoundingBox(pts).center)
            w = min(people,key=lambda w:math.dist(w['feet_ue_cm'],centre))
            yaw = (w['facing_ue_yaw_deg']-90+180)%360-180
            t['surfaces'].append({'source_handle':h,'center_ue_cm':centre,'size_cm':[180.,100.],
                                  'yaw_deg':yaw,'worker_source_handle':w['source_handle'],
                                  'source_vertices_ue_cm':[ue(p) for p in pts]})
        tables.append(t)
    assert len(tables) == 42
    data = {'source': str(SOURCE), 'source_sha256': digest, 'count': len(workers),
            'central_feed_count': 6, 'additional_count': 250, 'block_chain_counts': dict(counts),
            'coordinate_basis': {'dxf_origin': [12800., 8000.], 'to_ue_cm': '[2.54*(x-12800),-2.54*(y-8000),0]',
                                 'xy_anchor': 'Original head/torso projection centre, excluding forward arms and toes; prior bbox anchors retained for comparison.',
                                 'yaw': 'Transformed local +X working direction, including parent mirror; UE reflects CAD Y.',
                                 'z': 'Display floor z=0; source plan does not certify elevation.'},
            'audit': {'modelspace_recursive': True, 'includes_nested_gie2_and_anonymous_blocks': True,
                      'wrapper_children_counted_once': True, 'minimum_person_separation_cm': separation,
                      'excluded_named_assembly': '小黄人 is a large equipment assembly, not a personnel symbol; recursively checked for recognized personnel anyway.'},
            'workers': workers, 'work_tables': tables}
    (OUT / 'cad_workers.json').write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
    emit_header(data)

    # Two source symbol sheets make the local heading reviewable.
    for name, filename in [('terwrq434', 'person_symbol.png'), ('作业工人', 'worker_symbol.png'), ('GIE2', 'gie2_table_audit.png')]:
        lines = []

        def draw_entities(entities, mt, ancestors=()):
            for e in entities:
                if e.dxftype() == 'INSERT':
                    if e.dxf.name not in ancestors:
                        draw_entities(doc.blocks[e.dxf.name], Matrix44.chain(e.matrix44(), mt), ancestors + (e.dxf.name,))
                elif e.dxftype() in ('LINE', 'LWPOLYLINE', 'POLYLINE', 'ARC', 'CIRCLE', 'ELLIPSE', 'SPLINE'):
                    try:
                        pts = list(mt.transform_vertices(path.make_path(e).flattening(1)))
                        if len(pts) > 1:
                            lines.append(pts)
                    except (TypeError, ValueError, NotImplementedError):
                        pass

        draw_entities(doc.blocks[name], Matrix44())
        bb = BoundingBox(p for line in lines for p in line)
        assert bb.has_data
        scale = 650 / max(bb.size.x, bb.size.y)
        im = Image.new('RGB', (800, 800), 'white'); dr = ImageDraw.Draw(im)
        def q(p): return (75+(p.x-bb.extmin.x)*scale, 725-(p.y-bb.extmin.y)*scale)
        for line in lines:
            dr.line([q(p) for p in line], fill='#173247', width=2)
        if name == 'GIE2':
            for e in doc.blocks[name]:
                if e.dxftype() == 'INSERT' and e.dxf.name == 'terwrq434':
                    p = q(e.matrix44().transform(head_bounds.center))
                    dr.ellipse((p[0]-7,p[1]-7,p[0]+7,p[1]+7),fill='#df5b2a')
            dr.text((35, 45), 'Two source tables: 180 x 100 cm each | orange: standing body anchors', fill='#173247')
        else:
            p = q(anchor(name)[0]);dr.ellipse((p[0]-7,p[1]-7,p[0]+7,p[1]+7),fill='#df5b2a')
        dr.text((35, 20), 'Original CAD symbol | local +X ->', fill='#173247')
        im.save(OUT / filename)
    # Overview uses the existing source extraction only as a footprint backdrop;
    # every coloured person comes from the fresh recursive scan above.
    extracted = json.loads((ROOT / 'SourceAssets/MPR/mpr_cad_extracted.json').read_text(encoding='utf8'))
    im = Image.new('RGB', (2200, 1350), '#f6f8fa'); dr = ImageDraw.Draw(im)
    font = ImageFont.truetype('C:/Windows/Fonts/msyh.ttc', 28)
    small = ImageFont.truetype('C:/Windows/Fonts/msyh.ttc', 20)
    def qworld(p): return (70 + (p[0]-5400)*.138, 1240-(p[1]-4200)*.138)
    for category in ('racks', 'equipment'):
        for item in extracted[category]:
            if item['block'] in PERSON_BLOCKS:
                continue
            lo, hi = item['bounds_dxf']
            if not (5400 <= item['center_dxf'][0] <= 20200 and 4200 <= item['center_dxf'][1] <= 11400):
                continue
            dr.rectangle([qworld([lo[0], hi[1]]), qworld([hi[0], lo[1]])], outline='#d3dce3', width=1)
    for w in workers:
        p = qworld(w['body_anchor_dxf'])
        colour = '#df5b2a' if w['central_feed'] else '#087964' if len(w['source_handles']) > 1 else '#215caf'
        dr.ellipse((p[0]-4, p[1]-4, p[0]+4, p[1]+4), fill=colour)
        dx, dy, _ = w['axis']; length = math.hypot(dx, dy)
        dr.line((p, (p[0]+dx/length*12, p[1]-dy/length*12)), fill=colour, width=2)
    dr.text((70, 25), 'MPR 原 CAD 全部人员：256 个位置，6 个既有中央上料岗 + 250 个新增岗位', font=font, fill='#173247')
    dr.text((70, 80), '橙色：中央上料 6 人   蓝色：其余顶层人员 160 人   绿色：设备块内嵌人员 90 人；短线表示朝向', font=small, fill='#173247')
    dr.text((70, 130), '原始 INSERT 链和镜像变换完整保留；不在设备格口上推测添加人员。', font=small, fill='#173247')
    im.save(OUT / 'cad_workers_overview.png')
    print(json.dumps({'count': len(workers), 'patterns': dict(counts), 'minimum_separation_cm': separation}, ensure_ascii=False), flush=True)


if __name__ == '__main__':
    main()
